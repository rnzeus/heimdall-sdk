// Writes src/cloud-url.generated.ts: the production heimdall-cloud, or with HEIMDALL_CLOUD=local the one running on
// this computer, at its current LAN address so a real device reaches it too. Metro runs it on start; so can you.
// --if-missing only creates the file, so a type check never switches a running Metro to another cloud.
const {writeFileSync, readFileSync} = require('fs');
const {networkInterfaces} = require('os');
const path = require('path');

const PRODUCTION_CLOUD_URL = 'https://heimdall.rnzeus.dev';
const PRIVATE = [/^10\./, /^192\.168\./, /^172\.(1[6-9]|2\d|3[01])\./];
const TARGET = path.join(__dirname, '..', 'src', 'cloud-url.generated.ts');

const lanAddress = () => {
  const addresses = Object.entries(networkInterfaces()).flatMap(([name, list]) =>
    (list ?? []).filter(item => item.family === 'IPv4' && !item.internal).map(item => ({name, address: item.address})),
  );
  const isPrivate = ({address}) => PRIVATE.some(range => range.test(address));
  // Wi-Fi or Ethernet first: VPN and virtual adapters come with their own private ranges.
  const physical = addresses.filter(item => isPrivate(item) && /^(en|eth|wlan|Wi-Fi|Ethernet)/i.test(item.name));
  return (physical[0] ?? addresses.find(isPrivate) ?? addresses[0])?.address;
};

function writeCloudUrl() {
  const isLocal = process.env.HEIMDALL_CLOUD === 'local';
  const address = isLocal ? lanAddress() : null;
  if (isLocal && !address) throw new Error('HEIMDALL_CLOUD=local: no network address found');
  const url = isLocal ? `http://${address}:${process.env.HEIMDALL_CLOUD_PORT ?? '5173'}` : PRODUCTION_CLOUD_URL;
  const content = `// Generated by scripts/cloud-url.cjs, not committed.\nexport const CLOUD_URL = '${url}';\n`;
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {}
  if (current !== content) writeFileSync(TARGET, content);
  return url;
}

module.exports = {writeCloudUrl};

if (require.main === module) {
  let exists = true;
  try {
    readFileSync(TARGET);
  } catch {
    exists = false;
  }
  if (!(process.argv.includes('--if-missing') && exists)) console.log(`heimdall-cloud: ${writeCloudUrl()}`);
}
